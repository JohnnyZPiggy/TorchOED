library(skpr)
out <- Sys.getenv("R_ORACLE_OUT")
set.seed(20261120)
factorial = expand.grid(A = c(1, -1), B = c(1, -1), C = c(1, -1))
optdesign = gen_design(candidateset = factorial, model = ~A + B + C, trials = 11, optimality = "D", repeats = 100)
r1 <- eval_design(optdesign)
set.seed(20261120)
factorialcoffee = expand.grid(cost = c(1, 2), type = as.factor(c("Kona", "Colombian", "Ethiopian", "Sumatra")), size = as.factor(c("Short", "Grande", "Venti")))
designcoffee = gen_design(factorialcoffee, ~cost + size + type, trials = 29, optimality = "D", repeats = 100)
r2 <- eval_design(designcoffee)
write.csv(optdesign, file.path(out, "simple.csv"), row.names=FALSE)
write.csv(designcoffee, file.path(out, "coffee.csv"), row.names=FALSE)
results <- lapply(list(simple=r1, coffee=r2), function(r) list(power=r, anticoef=attr(r,"anticoef"), columns=colnames(attr(r,"model_matrix")), model_matrix=attr(r,"model_matrix")))
jsonlite::write_json(results, file.path(out,"reference.json"), dataframe="rows", auto_unbox=TRUE, pretty=TRUE, digits=17)
print(r1); print(r2)
