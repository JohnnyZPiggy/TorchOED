library(lmerTest)
options(digits=17)
out <- Sys.getenv("R_ORACLE_OUT")
d <- read.csv("reports/w17-reml-check/Oats.csv")
d$Variety <- factor(d$Variety, levels=sort(unique(d$Variety)))
d$nitro <- as.numeric(d$nitro)
ctl <- lmerControl(optimizer="nloptwrap", optCtrl=list(ftol_abs=1e-14, xtol_abs=1e-14, maxeval=10^5))
fit <- lmer(yield ~ Variety * factor(nitro) + (1 | Block/Variety), d, REML=TRUE, control=ctl)
nd <- expand.grid(nitro=c(0,.2,.4,.6), Variety=levels(d$Variety))
cells <- model.matrix(~ Variety * factor(nitro), nd)
L <- rbind(cells, do.call(rbind, lapply(levels(d$Variety), function(v) colMeans(cells[nd$Variety==v,,drop=FALSE]))),
           do.call(rbind, lapply(c(0,.2,.4,.6), function(n) colMeans(cells[nd$nitro==n,,drop=FALSE]))), colMeans(cells))
labels <- c(paste0("cell_",nd$Variety,"_",nd$nitro), paste0("variety_",levels(d$Variety)), paste0("nitro_",c(0,.2,.4,.6)), "grand")
write.csv(data.frame(row=labels,L,check.names=FALSE), file.path(out,"L.csv"), row.names=FALSE)
co <- contest(fit,L,joint=FALSE,confint=TRUE,level=.95)
q <- expand.grid(df=c(.5,1.5,2.7,5.5,9.31,17.4,44.1,80.2,300), level=c(.5,.9,.95,.99))
q <- rbind(q,data.frame(df=co$df,level=.95))
q$t <- qt(1-(1-q$level)/2,q$df)
jsonlite::write_json(list(rows=labels,contest=co[,c("Estimate","Std. Error","df","lower","upper")],
  fixef=fixef(fit),variance=as.data.frame(VarCorr(fit)),qt=q), file.path(out,"r.json"),digits=NA,auto_unbox=TRUE,pretty=TRUE)
